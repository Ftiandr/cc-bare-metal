#!/usr/bin/env python3
"""Generate src/main/resources/ccbaremetal/font/compose.txt.

Lists accented letters as "+ XXXX BASE MARK" using Unicode canonical decompositions, for every letter whose base
glyph exists in glyphs.txt (or is itself composable) and whose combining mark the font renderer knows how to draw.
"""
import os
import re
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "..", "src", "main", "resources", "ccbaremetal", "font")
MARKS = {0x0300, 0x0301, 0x0302, 0x0303, 0x0304, 0x0306, 0x0307, 0x0308, 0x030A, 0x030B, 0x030C,
         0x0323, 0x0326, 0x0327, 0x0328}
RANGES = [(0x00C0, 0x024F), (0x0400, 0x04FF), (0x1E00, 0x1EFF)]

defined = set()
for line in open(os.path.join(FONT, "glyphs.txt"), encoding="utf-8"):
    m = re.match(r"@([0-9A-Fa-f]{4,5})", line)
    if m:
        defined.add(int(m.group(1), 16))
    m = re.match(r"= ([0-9A-Fa-f]{4,5}) ", line)
    if m:
        defined.add(int(m.group(1), 16))

entries = []
known = set(defined)
changed = True
while changed:
    changed = False
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            if cp in known:
                continue
            dec = unicodedata.decomposition(chr(cp))
            if not dec or dec.startswith("<"):
                continue
            parts = [int(x, 16) for x in dec.split()]
            if len(parts) != 2 or parts[1] not in MARKS:
                continue
            base, mark = parts
            if base == ord("i"):
                base = 0x0131
            elif base == ord("j"):
                base = 0x0237
            if base not in known:
                continue
            entries.append((cp, base, mark))
            known.add(cp)
            changed = True

with open(os.path.join(FONT, "compose.txt"), "w", encoding="utf-8") as out:
    out.write("# Generated by scripts/gen_font_compose.py - accented letters as base + combining mark.\n")
    for cp, base, mark in sorted(entries):
        out.write("+ %04X %04X %04X  # %s\n" % (cp, base, mark, chr(cp)))
print(len(entries), "composed glyphs")
