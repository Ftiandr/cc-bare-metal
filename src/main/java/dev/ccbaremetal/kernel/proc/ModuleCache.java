package dev.ccbaremetal.kernel.proc;

import com.dylibso.chicory.compiler.Cache;
import com.dylibso.chicory.compiler.InterpreterFallback;
import com.dylibso.chicory.compiler.MachineFactoryCompiler;
import com.dylibso.chicory.runtime.Instance;
import com.dylibso.chicory.runtime.Machine;
import com.dylibso.chicory.wasm.Parser;
import com.dylibso.chicory.wasm.WasmModule;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.function.Function;

/**
 * Parsed and JIT-compiled WASM modules, keyed by content hash and shared by every machine on the server. Chicory
 * compiles each module to JVM bytecode once; afterwards starting a program (ls, cat...) only costs an instantiation.
 *
 * <p>With {@link #setDiskCache} the generated bytecode is also kept on disk, so big programs (the clang toolchain
 * takes minutes to translate) are only compiled once per installation, not once per server start.
 */
public final class ModuleCache {
    private static final Logger LOG = LoggerFactory.getLogger(ModuleCache.class);
    private static final int CAPACITY = 128;

    public record Compiled(WasmModule module, Function<Instance, Machine> machines, String hash) {
    }

    private static final Map<String, CompletableFuture<Compiled>> CACHE = new LinkedHashMap<>(16, 0.75f, true) {
        @Override
        protected boolean removeEldestEntry(Map.Entry<String, CompletableFuture<Compiled>> eldest) {
            return size() > CAPACITY;
        }
    };

    private static volatile Path diskCache;

    private ModuleCache() {
    }

    /** Directory for compiled bytecode (null disables the disk cache). */
    public static void setDiskCache(Path dir) {
        diskCache = dir;
    }

    /**
     * Chicory's cache interface: entries bundled in the mod jar (ccbaremetal/jit/, made at build time for the toolchain),
     * then files named by key in the disk cache directory, written atomically.
     */
    private record DiskCache(Path dir) implements Cache {
        private static String fileName(String key) {
            return key.replaceAll("[^A-Za-z0-9._-]", "_") + ".bin";
        }

        @Override
        public byte[] get(String key) throws IOException {
            try (var bundled = ModuleCache.class.getResourceAsStream("/ccbaremetal/jit/" + fileName(key))) {
                if (bundled != null) return bundled.readAllBytes();
            }
            if (dir == null) return null;
            var f = dir.resolve(fileName(key));
            return Files.exists(f) ? Files.readAllBytes(f) : null;
        }

        @Override
        public void putIfAbsent(String key, byte[] data) throws IOException {
            if (dir == null) return;
            var f = dir.resolve(fileName(key));
            if (Files.exists(f)) return;
            Files.createDirectories(dir);
            var tmp = Files.createTempFile(dir, "tmp", ".part");
            try {
                Files.write(tmp, data);
                Files.move(tmp, f, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
            } finally {
                Files.deleteIfExists(tmp);
            }
        }
    }

    public static String hash(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }

    public static Compiled get(byte[] bytes) throws Exception {
        var key = hash(bytes);
        CompletableFuture<Compiled> future;
        var owner = false;
        synchronized (CACHE) {
            future = CACHE.get(key);
            if (future == null) {
                future = new CompletableFuture<>();
                CACHE.put(key, future);
                owner = true;
            }
        }
        if (owner) {
            try {
                var start = System.nanoTime();
                var module = Parser.parse(bytes);
                var builder = MachineFactoryCompiler.builder(module).withInterpreterFallback(InterpreterFallback.SILENT);
                var machines = builder.withCache(new DiskCache(diskCache)).compile();
                LOG.info("Prepared WASM module {} ({} KiB) in {} ms", key.substring(0, 12), bytes.length / 1024,
                    (System.nanoTime() - start) / 1_000_000);
                future.complete(new Compiled(module, machines, key));
            } catch (Throwable t) {
                synchronized (CACHE) {
                    CACHE.remove(key);
                }
                future.completeExceptionally(t);
            }
        }
        try {
            return future.get();
        } catch (java.util.concurrent.ExecutionException e) {
            if (e.getCause() instanceof Exception ex) throw ex;
            throw e;
        }
    }

    public static void clear() {
        synchronized (CACHE) {
            CACHE.clear();
        }
    }
}
